// Captures key gameplay moments for visual review (not pass/fail).
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = ROOT + '/tests/screenshots';
const b = await chromium.launch();
const p = await b.newPage({viewport:{width:1280, height:720}});
await p.goto('file://' + ROOT + '/dist/preview/full.html?debug=1');
const shot = async (name, fn) => { await p.evaluate(fn); await p.waitForTimeout(60); await p.screenshot({path:`${OUT}/moment-${name}.png`}); };
await shot('start', () => {});
await p.click('#btnPlay');
const setup = (lvl, x, steps, keys) => `(() => { const D = window.Razebait.debug; D.setLoopPaused(true); D.start(${lvl}); const ls = D.level();
  document.getElementById('worldToast').classList.remove('show');
  ls.player.x = ${x}; ${keys||''}; D.step(${steps}); })()`;
await shot('l1-door-moves', setup(0, 1690, 20, "D.press('right', true)"));
await shot('l2-collapse', setup(1, 760, 50, "D.press('right', false)"));
await shot('l3-crusher-warning', setup(2, 1995, 50, "D.press('right', true)"));
await shot('l3-checkpoint', setup(2, 1745, 10, "ls.player.y = 498; D.press('right', false)"));
await shot('l4-chaser', `(() => { const D = window.Razebait.debug; D.setLoopPaused(true); D.start(3); document.getElementById('worldToast').classList.remove('show'); D.press('right', true); D.step(130); D.press('right', false); D.step(150); })()`);
await shot('l5-door-hop', setup(4, 3010, 26, "D.press('right', true)"));
await shot('death-burst', `(() => { const D = window.Razebait.debug; D.setLoopPaused(true); D.start(2); document.getElementById('worldToast').classList.remove('show'); D.press('right', true); for (let i=0;i<400 && D.state()==='playing';i++) D.step(1); D.step(8); })()`);
await p.evaluate(() => { const D = window.Razebait.debug; D.press('right', false); D.start(0); const ls = D.level(); ls.goal.x = ls.player.x - 18; ls.goal.y = ls.player.y - 38; D.setLoopPaused(false); });
await p.waitForTimeout(800);
await p.screenshot({path:`${OUT}/moment-win.png`});
await p.keyboard.press('Escape');
await p.evaluate(() => { document.getElementById('btnWinMenu').click(); });
await p.waitForTimeout(200);
await p.screenshot({path:`${OUT}/moment-levelselect.png`});
await b.close();
